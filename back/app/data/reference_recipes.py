# 매칭 함수
# ─────────────────────────────────────────────────────────

_WHITESPACE_RE = re.compile(r"\s+")


def _normalize(text: str) -> str:
    """간단한 정규화: 소문자 + strip + 공백 정리"""
    return _WHITESPACE_RE.sub("", text.strip().lower())


def _is_match(user_ing: str, ref_ing: str) -> bool:
    """부분매칭 — 어느 한쪽이 다른 쪽에 포함되면 매칭"""
    u = _normalize(user_ing)
    r = _normalize(ref_ing)
    if not u or not r:
        return False
    return u in r or r in u


def match_references(ingredients: list[str], count: int = 5) -> list[dict]:
    """사용자 재료와 매칭되는 레퍼런스 레시피 반환 (매칭수 내림차순)

    매칭 로직:
    1. normalize (소문자, 공백 제거)
    2. 부분매칭: 사용자 재료가 key_ingredients에 포함되거나 그 역
    3. 점수 = 매칭된 재료 수
    4. 동점 시 랜덤 셔플로 다양성 확보
    5. 상위 count개 반환
    """
    scored: list[tuple[int, dict]] = []

    for recipe in REFERENCE_RECIPES:
        matched = 0
        for user_ing in ingredients:
            for ref_ing in recipe["key_ingredients"]:
                if _is_match(user_ing, ref_ing):
                    matched += 1
                    break  # 같은 user_ing에 대해 중복 카운트 방지
        if matched > 0:
            scored.append((matched, recipe))

    # 동점 시 랜덤 셔플
    random.shuffle(scored)
    scored.sort(key=lambda x: x[0], reverse=True)

    return [recipe for _, recipe in scored[:count]]
